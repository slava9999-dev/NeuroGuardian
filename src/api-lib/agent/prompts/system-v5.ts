/**
 * Build complete planner prompt
 */
export function buildPlannerPrompt(userContext?: {
  marketplace?: string;
  productsCount?: number;
  onboardingMode?: boolean;
  userName?: string;
}): string {
  let contextSection = '';

  if (userContext) {
    contextSection = `

## КОНТЕКСТ ПРОДАВЦА
- Имя: ${userContext.userName || 'Продавец'}
- Маркетплейс: ${userContext.marketplace || 'не указан'}
- Товаров: ${userContext.productsCount || 0}
${userContext.onboardingMode ? '- ⚠️ КЛЮЧИ НЕ ПОДКЛЮЧЕНЫ — нужен onboarding!' : ''}
`;
  }

  const onboardingInstruction = userContext?.onboardingMode
    ? `

### ВАЖНО!
У продавца не подключены ключи. Ты НЕ можешь получить данные о товарах.
Твоя задача: вежливо объяснить как подключить магазин.
Направь в настройки. НЕ вызывай инструменты требующие данных магазина.
Можешь использовать search_web для общих вопросов.`
    : '';

  return PLANNER_PROMPT_V5 + contextSection + onboardingInstruction + PLANNER_ADDITION;
}

