/**
 * Build complete planner prompt with user context
 */
export function buildPlannerPrompt(userContext?: {
  marketplace?: string;
  productsCount?: number;
  onboardingMode?: boolean;
  userName?: string;
  isFirstContact?: boolean;
  hasSyncedProducts?: boolean;
}): string {
  let contextSection = '';

  if (userContext) {
    contextSection = `

## КОНТЕКСТ ПРОДАВЦА
- Имя: ${userContext.userName || 'Продавец'}
- Маркетплейс: ${userContext.marketplace || 'не указан'}
- Товаров: ${userContext.productsCount || 0}
- Первый контакт: ${userContext.isFirstContact ? 'ДА — нужно вступить в роль!' : 'нет'}
- Товары синхронизированы: ${userContext.hasSyncedProducts ? 'да' : 'нет'}
${userContext.onboardingMode ? '- ⚠️ КЛЮЧИ НЕ ПОДКЛЮЧЕНЫ — нужен onboarding!' : ''}
`;
  }

  let specialInstructions = '';

  // Первый контакт — особые правила
  if (userContext?.isFirstContact) {
    specialInstructions = `

### 🎯 ПЕРВЫЙ КОНТАКТ — КРИТИЧЕСКИ ВАЖНО!
Это ПЕРВОЕ сообщение пользователя. Ты ОБЯЗАН:
1. Поприветствовать по имени
2. Подтвердить вступление в должность управляющего
3. Объяснить что умеешь КРАТКО
4. Проверить есть ли доступ к магазину

НЕ вызывай инструменты при первом контакте если это просто приветствие.
Вместо этого — вернись пустым tools и сгенерируй персональное приветствие.`;
  }

  // Онбординг — ключи не подключены
  if (userContext?.onboardingMode) {
    specialInstructions += `

### 🔐 ОНБОРДИНГ
У продавца не подключены ключи API. 
НЕ вызывай инструменты требующие данных магазина!
Помоги подключить ключи. Направь в настройки.
Можешь использовать search_web для общих вопросов о маркетплейсах.`;
  }

  // Есть ключи но нет товаров
  if (!userContext?.onboardingMode && !userContext?.hasSyncedProducts) {
    specialInstructions += `

### 🔄 СИНХРОНИЗАЦИЯ НУЖНА
Ключи подключены, но товары не синхронизированы.
Предложи запустить синхронизацию перед анализом.`;
  }

  return PLANNER_PROMPT_V5 + contextSection + specialInstructions + PLANNER_ADDITION;
}

